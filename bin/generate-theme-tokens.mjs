#!/usr/bin/env node
/**
 * Generate Tailwind v4 colour tokens from any number of named client colours
 * (minimum 3 — see MINIMUM_COLORS below), plus one re-themeable "section"
 * per colour (buildSectionThemesCss) for skinning a whole block/section at
 * once via a `theme-{name}` or `theme-{alias}` class, and two opt-in "card"
 * recolour variants per section (buildCardThemesCss).
 *
 * Every colour can carry a `role` ("brand"/"accent"/"black"/"white" — see
 * ROLES below) decoupling *what a colour is called* from *what part it
 * plays* (buildCss's --color-action/--color-highlight, and which colour a
 * `card` pointer defaults to), and a `styles` object (background/content/
 * highlight/buttons/border/card) computed once and never touched again —
 * see backfillStyles()'s own comment, and docs/planning/themed-cards-reference.md
 * for the full design this implements.
 *
 * Usage:
 *   node bin/generate-theme-tokens.mjs \
 *     --color brand=#2563eb --color accent=#f97316 --color highlight=#16a34a \
 *     --display-font Poppins --sans-font Inter [--mono-font "IBM Plex Mono"]
 *
 * --mono-font is optional — most projects never need a third, monospace
 * font.
 *
 * Fonts themselves are NOT generated by this script — it only validates
 * `config/brand-palette.json`'s `fonts` object and writes it back unchanged.
 * The actual self-hosted @font-face CSS, preloading, and CLS-safe fallback
 * fonts are generated by vite.config.js's own `fonts:` option (reads this
 * same config directly) via laravel-vite-plugin's official Fonts feature —
 * see that file's own comment, and web/app/themes/sage/docs/branding-tokens.md
 * for the full explanation, including how to point a font slot at your own
 * font files instead of a Google Fonts family name.
 *
 * The generated CSS must not be hand-edited. Change config/brand-palette.json
 * (or rerun this command) and generate it again instead.
 */
import fs from 'node:fs';
import path from 'node:path';
import { converter, formatHex, wcagContrast } from 'culori';

// The theme's directory: where `npm run theme:generate` runs (package.json scripts call this file from vendor/pkde/sage-kit/bin),
// or PKDE_THEME_DIR. Never a path relative to this file, which lives in vendor/.
const themeDirectory = path.resolve(process.env.PKDE_THEME_DIR || process.cwd());
const rootDirectory = path.resolve(themeDirectory, '../../../..');
const configPath = path.join(rootDirectory, 'config/brand-palette.json');
const outputPath = path.join(themeDirectory, 'resources/css/generated/brand-tokens.css');
const sectionThemesOutputPath = path.join(themeDirectory, 'resources/css/generated/section-themes.css');
const cardThemesOutputPath = path.join(themeDirectory, 'resources/css/generated/card-themes.css');
const themeJsonPath = path.join(themeDirectory, 'theme.json');
const themeOptionsOutputPath = path.join(themeDirectory, 'resources/js/generated/theme-options.js');
const themeOptionsPhpOutputPath = path.join(themeDirectory, 'resources/generated/theme-options.php');
const headerOptionsOutputPath = path.join(themeDirectory, 'resources/generated/header-options.php');
const toOklch = converter('oklch');

const shadeLightness = { 50: 0.97, 100: 0.94, 200: 0.88, 300: 0.8, 400: 0.71, 500: 0.62, 700: 0.46, 800: 0.36, 900: 0.27, 950: 0.18 };
const steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// Tailwind's own neutral greys, by lightness. The views and blocks use neutral-* for text, borders and quiet
// surfaces; buildCss() redefines the scale at these same lightnesses with a faint tint of the brand hue, so a
// rebranded site's greys follow its brand without touching any view.
const neutralLightness = { 50: 0.985, 100: 0.97, 200: 0.922, 300: 0.87, 400: 0.708, 500: 0.556, 600: 0.439, 700: 0.371, 800: 0.269, 900: 0.205, 950: 0.145 };

// Positional, brand-agnostic stand-ins for every named colour (theme-brand
// and theme-alpha always refer to the same generated theme — see
// buildSectionThemesCss below) — a dev who doesn't know this client's brand
// vocabulary yet can reach for "alpha"/"bravo" instead of "danger"/"teal".
// NATO alphabet rather than a short greek/lettered list since a palette can
// have more than a handful of colours and this still reads unambiguously at
// any length.
const POSITIONAL_ALIASES = [
  'alpha', 'bravo', 'charlie', 'delta', 'echo', 'foxtrot', 'golf', 'hotel',
  'india', 'juliett', 'kilo', 'lima', 'mike', 'november', 'oscar', 'papa',
  'quebec', 'romeo', 'sierra', 'tango', 'uniform', 'victor', 'whiskey',
  'xray', 'yankee', 'zulu',
];

// Reserved roles — decoupled from a colour's own `name` so a client's real
// brand colour doesn't have to literally be *called* "brand" for the system
// that depends on one existing to work (buildCss's --color-action/-highlight,
// component classes like bg-brand-600 already hardcoded in several Blade
// partials — see buildCss's own comment). Exactly one colour may hold each.
const ROLES = ['brand', 'accent', 'black', 'white'];

const MINIMUM_COLORS = 3;

function fail(message) {
  process.stderr.write(`Error: ${message}\n`);
  process.exit(1);
}

function slugify(value) {
  return value.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function parseArguments() {
  const result = { colors: [], displayFont: null, sansFont: null, monoFont: null, dryRun: false, check: false };
  const args = process.argv.slice(2);

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === '--color') {
      const pair = args[++index] ?? '';
      const [name, hex] = pair.split('=', 2);
      result.colors.push({ name, hex });
    } else if (argument === '--display-font') {
      result.displayFont = args[++index] ?? '';
    } else if (argument === '--sans-font') {
      result.sansFont = args[++index] ?? '';
    } else if (argument === '--mono-font') {
      result.monoFont = args[++index] ?? '';
    } else if (argument === '--dry-run') {
      result.dryRun = true;
    } else if (argument === '--check') {
      result.check = true;
    } else {
      fail(`Unknown argument: ${argument}`);
    }
  }

  return result;
}

/**
 * Validates/normalises the raw colour list, then resolves `role`: a colour
 * literally named "brand"/"accent"/"black"/"white" gets that role
 * automatically unless it already has a different explicit role of its own
 * — every existing palette (this template's own default included) already
 * names its colours this way, so nothing has to add an explicit `role`
 * field just to keep working exactly as before. Two colours claiming the
 * same role (whether explicit, inferred, or one of each) is ambiguous —
 * which one is actually "brand"? — and fails loudly rather than silently
 * picking one.
 */
function validatePalette(colors) {
  if (colors.length < MINIMUM_COLORS) {
    fail(`At least ${MINIMUM_COLORS} colours are required (brand, accent, and at least one more) — section themes (see buildSectionThemesCss) need real variety to draw from, and the block demo page seeds one example per theme.`);
  }

  const names = new Set();
  const validated = colors.map(({ name, hex, role, styles }) => {
    const slug = slugify(name ?? '');
    if (!slug) fail(`Invalid colour name: ${name}`);
    if (!/^#[0-9a-f]{6}$/i.test(hex ?? '')) fail(`${name} must use a 6-digit hex value.`);
    if (names.has(slug)) fail(`Duplicate colour name: ${slug}`);
    names.add(slug);
    if (role !== undefined && !ROLES.includes(role)) {
      fail(`${name} has an unrecognised role "${role}" — must be one of: ${ROLES.join(', ')}.`);
    }
    const result = { name: slug, hex: hex.toLowerCase() };
    if (role !== undefined) result.role = role;
    if (styles !== undefined) result.styles = styles;
    return result;
  });

  for (const color of validated) {
    if (color.role === undefined && ROLES.includes(color.name)) {
      color.role = color.name;
    }
  }

  const roles = new Set();
  for (const color of validated) {
    if (color.role === undefined) continue;
    if (roles.has(color.role)) {
      fail(`More than one colour has role "${color.role}" (including "${color.name}") — only one colour may hold each reserved role.`);
    }
    roles.add(color.role);
  }

  return validated;
}

/**
 * Every theme ships a near-black and near-white to pick text/cards from —
 * see backfillStyles() — so exactly one colour must hold role "black" and
 * one "white". If neither is set (the common case: a fresh palette, or an
 * older one from before this existed), auto-adds plain #000000/#ffffff
 * defaults — a client can hand-edit their hex later (a warm near-black, a
 * cream near-white) exactly the way any other colour gets hand-tuned, per
 * docs/planning/themed-cards-reference.md.
 */
function ensureNeutralRoles(colors) {
  const names = new Set(colors.map((color) => color.name));
  const defaults = [
    ['black', '#000000'],
    ['white', '#ffffff'],
  ];

  for (const [role, hex] of defaults) {
    if (colors.some((color) => color.role === role)) continue;
    if (names.has(role)) {
      fail(`No colour has role "${role}" and the auto-generated default name "${role}" is already taken by another colour — rename that colour, or add "role": "${role}" to whichever one should hold it.`);
    }
    colors.push({ name: role, hex, role });
    names.add(role);
  }

  return colors;
}

// The 600 step normally *is* the exact source colour (distance 0 below), so
// it reads back precisely what was typed in. But a bright/light source (a
// saturated yellow, say) can have a natural lightness above 500's fixed
// 0.62 — left unclamped, 600 would then render lighter than 500, breaking
// the scale's monotonic darkening (confirmed on #eab308: 600 came out
// lighter than 500 and nearly as light as 300). Clamping keeps 600 exactly
// on the source for every colour that was already well-behaved, and only
// pulls outliers back into a band strictly between 500 and 700 (with a
// small margin so 600 never lands exactly on either neighbour) rather than
// letting them invert the scale.
const SIX_HUNDRED_MIN = shadeLightness[700] + 0.01;
const SIX_HUNDRED_MAX = shadeLightness[500] - 0.01;

function shade(color, step) {
  const base = toOklch(color.hex);
  if (!base) fail(`Unable to convert ${color.hex}.`);
  const lightness = step === 600
    ? Math.min(SIX_HUNDRED_MAX, Math.max(SIX_HUNDRED_MIN, base.l))
    : shadeLightness[step];
  // Chroma falls toward both white and black, reducing out-of-gamut colours
  // while preserving the supplied hue and the exact source wherever a step's
  // lightness matches the source's own (always true at 600, unless clamped
  // above).
  const distance = Math.abs(lightness - base.l);
  const chroma = Math.max(0, base.c * (1 - distance * 1.15));
  // culori omits `h` entirely for a fully achromatic source (chroma 0 — a
  // pure #000000/#ffffff, the default role:black/role:white hex) since hue
  // is meaningless without any chroma to begin with. Falls back to 0 rather
  // than crashing; harmless either way once chroma is also 0.
  const hue = base.h ?? 0;
  return `oklch(${lightness.toFixed(3)} ${chroma.toFixed(3)} ${hue.toFixed(2)})`;
}

/**
 * Picks whichever of role:black/role:white has better *measured* WCAG
 * contrast against `candidate` (a shade() string — wcagContrast reads raw
 * CSS colour strings, oklch() included, directly). Ties favour white,
 * matching this system's own prior behaviour (every theme used plain white
 * content before this existed). This isn't a stylistic nicety — it's a real
 * correctness fix: the previous hardcoded "always white" broke down on
 * lighter source colours. Confirmed directly against this template's own
 * default palette: white on #f59e0b (accent) at its own 600 step measures
 * 2.15:1 — well under WCAG AA's 4.5:1 for normal text — against 9.78:1 for
 * black on the same colour.
 */
function pickNeutral(candidate, blackColor, whiteColor) {
  const blackRef = shade(blackColor, 950);
  const whiteRef = shade(whiteColor, 50);
  return wcagContrast(candidate, blackRef) > wcagContrast(candidate, whiteRef)
    ? { color: blackColor, step: 950 }
    : { color: whiteColor, step: 50 };
}

/**
 * Picks the step of `hueColor` to use as a "highlight" (an eyebrow, link or accent drawn on a section
 * background), starting from the step the design intends (`preferred`) and moving to whichever step is
 * nearest that still reads on `background` (a shade() string): at least 4.5:1, WCAG AA for normal text.
 * If no step of that hue reaches 4.5:1 the best-measured one wins. The fixed picks used before
 * (hue-200 on the colour's own 600) measured 2.6:1 and 3.5:1 on mid and cream colours.
 */
function pickHighlight(hueColor, background, preferred) {
  const ranked = [...steps]
    .sort((a, b) => Math.abs(a - preferred) - Math.abs(b - preferred) || a - b)
    .map((step) => ({ step, ratio: wcagContrast(shade(hueColor, step), background) }));
  const best = ranked.find((candidate) => candidate.ratio >= 4.5)
    ?? ranked.reduce((top, candidate) => (candidate.ratio > top.ratio ? candidate : top));
  return `${hueColor.name}-${best.step}`;
}

/**
 * Fills in a full `styles` object — background/content/highlight/button
 * colours/border/card — for any colour that doesn't already have one.
 * Computed once, then left alone forever after: a hand edit in
 * config/brand-palette.json is never recomputed or overwritten by a later
 * run, only ever backfilled for a colour that's missing it entirely (a
 * newly-added palette colour, or the first time this ever runs on an older
 * palette). See docs/planning/themed-cards-reference.md's "Proposed design"
 * for the full rationale, and pickNeutral() above for why content/button/
 * card colours are chosen by measured contrast rather than assumed.
 *
 * `card` — the one pointer field, not a shade reference like the others —
 * names another colour by its real `name`; whichever block/render.php reads
 * it resolves that colour's *own* `styles` wholesale for a themed card (see
 * buildCardThemesCss below). Always exactly one hop: a card never chases
 * whatever its own `card` might in turn point to.
 *
 * `buttonPrimaryText` always borrows the *content* rule of whichever colour
 * actually provides `buttonPrimaryBackground`, rather than guessing a shade
 * of its own hue — a button's background is always literally that other
 * colour's own background value, so "what text reads on it" is a question
 * that colour has already answered correctly for itself. That's a genuine
 * circular-looking dependency (brand's button sits on black or white;
 * black/white's own button sits on brand) — resolved with two passes rather
 * than a fixed processing order: every colour's `content` has no
 * cross-colour dependency at all (pickNeutral only ever reads raw hex), so
 * it's always safe to compute first for every colour; only once every
 * colour's `content` exists does the second pass fill in `buttonPrimaryText`
 * by reading whichever other colour's `content` its own button background
 * actually points at.
 */
function backfillStyles(colors) {
  const brand = colors.find((color) => color.role === 'brand') ?? colors[0];
  const blackColor = colors.find((color) => color.role === 'black');
  const whiteColor = colors.find((color) => color.role === 'white');

  for (const color of colors) {
    if (color.styles) continue;

    if (color.role === 'black' || color.role === 'white') {
      const isBlack = color.role === 'black';
      const backgroundStep = isBlack ? 950 : 50;
      const opposite = isBlack ? whiteColor : blackColor;
      const oppositeStep = isBlack ? 50 : 950;

      color.styles = {
        background: `${color.name}-${backgroundStep}`,
        content: `${opposite.name}-${oppositeStep}`,
        // A pure neutral has no hue of its own to build a highlight/button
        // accent from — borrow brand's, so a stark black/white section
        // still gets a branded call-to-action instead of looking generic.
        highlight: pickHighlight(brand, shade(color, backgroundStep), isBlack ? 200 : 600),
        buttonPrimaryBackground: `${brand.name}-600`,
        buttonSecondaryBackground: 'transparent',
        buttonSecondaryText: `${opposite.name}-${oppositeStep}`,
        border: `${color.name}-${isBlack ? 800 : 200}`,
        card: opposite.name,
      };
      continue;
    }

    const winner = pickNeutral(shade(color, 600), blackColor, whiteColor);
    const winnerRef = `${winner.color.name}-${winner.step}`;

    color.styles = {
      background: `${color.name}-600`,
      content: winnerRef,
      highlight: pickHighlight(color, shade(color, 600), 200),
      buttonPrimaryBackground: winnerRef,
      buttonSecondaryBackground: 'transparent',
      buttonSecondaryText: winnerRef,
      border: `${color.name}-500`,
      card: winner.color.name,
    };
  }

  // Second pass — every colour's `content` now exists (either just computed
  // above, or already there from a prior run), so `buttonPrimaryText` can
  // safely borrow it. `color.styles.buttonPrimaryText` is only ever unset
  // here for a colour whose whole `styles` object was just backfilled this
  // run — one with pre-existing `styles` from before this field existed (or
  // a hand-edit) already has *some* value here and is left alone, same as
  // every other field's "computed once" rule.
  for (const color of colors) {
    if (color.styles.buttonPrimaryText) continue;

    if (color.role === 'black' || color.role === 'white') {
      color.styles.buttonPrimaryText = brand.styles.content;
    } else {
      const winner = pickNeutral(shade(color, 600), blackColor, whiteColor);
      color.styles.buttonPrimaryText = winner.color.styles.content;
    }
  }

  return colors;
}

/**
 * The text colour for a background: white when it reaches 4.5:1 (the look the kit always had), otherwise whichever of white and
 * near-black measures higher. Emitted as --color-{name}-{step}-fg (text-brand-600-fg), so a component that sets text on a brand or
 * accent background never needs a hard-coded text-white that a light colour would turn unreadable.
 */
function foregroundFor(background) {
  const white = wcagContrast(background, '#ffffff');
  if (white >= 4.5) return '#ffffff';

  return wcagContrast(background, FOREGROUND_DARK) > white ? FOREGROUND_DARK : '#ffffff';
}
const FOREGROUND_DARK = '#0a0a0a';

function buildCss(colors) {
  const colourNames = colors.map((color) => color.name);
  const lines = [
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json.',
    ' * Do not edit directly.',
    ' */',
    '@theme {',
  ];

  for (const color of colors) {
    lines.push(`  /* ${color.name}: ${color.hex} */`);
    for (const step of steps) lines.push(`  --color-${color.name}-${step}: ${shade(color, step)};`);
    if (color.role !== 'black' && color.role !== 'white') {
      for (const step of steps) lines.push(`  --color-${color.name}-${step}-fg: ${foregroundFor(shade(color, step))};`);
      lines.push(`  --color-${color.name}-fg: ${foregroundFor(shade(color, 600))};`);
    }
    // The bare --color-{name} alias (a stand-in for "the" swatch, at step
    // 600) only makes sense for a normal colour, where 600 is close to what
    // a human actually picked. For role black/white it's actively wrong —
    // 600 is clamped into a mid-lightness band meant to keep a *saturated
    // brand colour* legible (SIX_HUNDRED_MIN/MAX above), which would turn a
    // true near-black/near-white into a flat mid-grey — and skipping it
    // also avoids colliding with Tailwind's own built-in --color-black/
    // --color-white if a palette colour is named exactly that.
    if (color.role !== 'black' && color.role !== 'white') {
      lines.push(`  --color-${color.name}: ${shade(color, 600)};`);
    }
    // The exact source hex, untouched by the 600-step clamp above and by oklch rounding, for the one
    // place a brand colour must match the client's own artwork exactly (bg-gold-exact, text-gold-exact).
    lines.push(`  --color-${color.name}-exact: ${color.hex};`);
    lines.push('');
  }

  const brand = colors.find((color) => color.role === 'brand') ?? colors[0];
  const accent = colors.find((color) => color.role === 'accent') ?? brand;

  // A client's real brand colour doesn't have to literally be *named*
  // "brand" any more (see the `role` field) — but several Blade partials
  // still reference bg-brand-600/hover:text-brand-700 etc. by that literal
  // class name (badges, hover/focus states — see resources/blocks/README.md).
  // Whenever the colour actually holding a reserved role has a different
  // real name, alias its whole scale under the role name too, so nothing
  // already written against "brand"/"accent" breaks.
  const roleAliases = [];
  for (const [role, color] of [['brand', brand], ['accent', accent]]) {
    if (color.name === role) continue;
    for (const step of steps) lines.push(`  --color-${role}-${step}: var(--color-${color.name}-${step});`, `  --color-${role}-${step}-fg: var(--color-${color.name}-${step}-fg);`);
    lines.push(`  --color-${role}-fg: var(--color-${color.name}-fg);`);
    lines.push(`  --color-${role}: var(--color-${color.name});`, `  --color-${role}-exact: var(--color-${color.name}-exact);`, '');
    roleAliases.push(role);
  }

  // Brand-tinted neutral greys (see neutralLightness). Chroma is a small fraction of the brand's, capped, so
  // they read as grey with a hint of the brand rather than as a second colour.
  const brandOklch = toOklch(brand.hex);
  const tint = Math.min(0.02, (brandOklch?.c ?? 0) * 0.12);
  const tintHue = (brandOklch?.h ?? 0).toFixed(2);
  lines.push('  /* neutral: brand-tinted replacement for Tailwind\'s grey scale */');
  for (const step of steps) {
    const neutral = `oklch(${neutralLightness[step]} ${tint.toFixed(3)} ${tintHue})`;
    lines.push(`  --color-neutral-${step}: ${neutral};`, `  --color-neutral-${step}-fg: ${foregroundFor(neutral)};`);
  }
  lines.push('');

  lines.push(
    `  --color-action: ${shade(brand, 600)};`,
    `  --color-action-hover: ${shade(brand, 700)};`,
    `  --color-highlight: ${shade(accent, 600)};`,
    `  --color-action-fg: ${foregroundFor(shade(brand, 600))};`,
    `  --color-action-hover-fg: ${foregroundFor(shade(brand, 700))};`,
    `  --color-highlight-fg: ${foregroundFor(shade(accent, 600))};`,
    '}',
    '',
    `@source inline("{bg,text,border,ring,fill,stroke,outline}-{${colourNames.concat(roleAliases).join(',')}}-{50,100,200,300,400,500,600,700,800,900,950}");`,
    `@source inline("text-{${colourNames.concat(roleAliases).join(',')}}-{50,100,200,300,400,500,600,700,800,900,950}-fg");`,
    `@source inline("{bg,text,border,ring,fill,stroke,outline}-{${colourNames.concat(roleAliases).join(',')}}");`,
    `@source inline("{bg,text,border,ring,fill,stroke,outline}-{${colourNames.concat(roleAliases).join(',')}}-exact");`,
    '@source inline("{bg,text,border,ring,fill,stroke,outline}-{action,action-hover,highlight}");',
    '',
  );
  return lines.join('\n');
}

/**
 * One re-themeable "section" per palette colour, addressable two ways —
 * .theme-{name} (the client's own vocabulary, e.g. .theme-danger) and
 * .theme-{alias} (a brand-agnostic positional stand-in, e.g. .theme-alpha)
 * always resolve to the exact same block, so a dev unfamiliar with this
 * client's palette can reach for the alias instead. Components (buttons,
 * hero/CTA sections, ...) must consume only these --pkde-theme-* tokens,
 * never --color-{name}-* directly, so wrapping any section in a theme class
 * re-skins everything inside it at once — see :root's own --pkde-theme-*
 * defaults in app.css for the "no theme class" fallback look.
 *
 * Every value here comes straight from the colour's own `styles` object
 * (backfillStyles() above) rather than being computed inline — edit
 * config/brand-palette.json's `styles` for a specific colour (a hand-picked
 * highlight, a different button pairing, a `card` pointer at a different
 * theme entirely) and rerun the generator to pick it up; nothing here
 * invents its own values any more.
 */
function buildSectionThemesCss(colors) {
  const lines = [
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json.',
    ' * Do not edit directly — edit each colour\'s own `styles` in',
    ' * config/brand-palette.json instead, then regenerate.',
    ' */',
  ];

  colors.forEach((color, index) => {
    const alias = POSITIONAL_ALIASES[index];
    const selectors = alias ? [`.theme-${color.name}`, `.theme-${alias}`] : [`.theme-${color.name}`];
    const s = color.styles;
    const altBtnBg = s.buttonSecondaryBackground === 'transparent' ? 'transparent' : `var(--color-${s.buttonSecondaryBackground})`;
    lines.push(`${selectors.join(',\n')} {`);
    lines.push(
      `  --pkde-theme-background: var(--color-${s.background});`,
      `  --pkde-theme-content: var(--color-${s.content});`,
      `  --pkde-theme-highlight: var(--color-${s.highlight});`,
      `  --pkde-theme-btn-bg: var(--color-${s.buttonPrimaryBackground});`,
      `  --pkde-theme-btn-text: var(--color-${s.buttonPrimaryText});`,
      `  --pkde-theme-btn-border: var(--color-${s.buttonPrimaryBackground});`,
      `  --pkde-theme-alt-btn-bg: ${altBtnBg};`,
      `  --pkde-theme-alt-btn-text: var(--color-${s.buttonSecondaryText});`,
      `  --pkde-theme-alt-btn-border: var(--color-${s.buttonSecondaryText});`,
      `  --pkde-theme-border: var(--color-${s.border});`,
      '}',
      '',
    );
  });

  return lines.join('\n');
}

/**
 * Two opt-in "card" recolour variants per palette colour — `.pkde-card-tinted`
 * and `.pkde-card-bold` — for any card marked with one of those classes
 * while sitting inside a themed section (`.theme-{name}`/`.theme-{alias}`,
 * see buildSectionThemesCss above). Cards don't carry a theme class
 * themselves, so these are descendant selectors, not standalone ones — see
 * docs/planning/themed-cards-reference.md's "Proposed design" for the full
 * rationale.
 *
 * - **Tinted**: a much lighter step (50) of the *same* colour as its
 *   section, with dark neutral text — safe for any hue, since every
 *   colour's own step 50 sits at the same ~0.97 lightness regardless of hue
 *   (shadeLightness above). Computed the same way regardless of `styles`.
 * - **Bold**: resolves `styles.card` — a real colour name — and borrows
 *   *that* colour's own `styles.background`/`content`/`highlight` wholesale,
 *   one hop, never chasing whatever that colour's own `card` might in turn
 *   point to. `styles.card` defaults to whichever of role:black/role:white
 *   measured better against this colour's own background (backfillStyles()
 *   above), but is a completely ordinary field — hand-edit it in
 *   config/brand-palette.json to point a theme's cards at any other colour
 *   in the palette instead.
 */
function buildCardThemesCss(colors) {
  const lines = [
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json.',
    ' * Do not edit directly — edit each colour\'s own `styles.card` in',
    ' * config/brand-palette.json instead, then regenerate.',
    ' */',
  ];

  colors.forEach((color, index) => {
    const alias = POSITIONAL_ALIASES[index];
    const baseSelectors = alias ? [`.theme-${color.name}`, `.theme-${alias}`] : [`.theme-${color.name}`];
    const cardColor = colors.find((candidate) => candidate.name === color.styles.card) ?? color;

    const tintedSelectors = baseSelectors.map((selector) => `${selector} .pkde-card-tinted`);
    lines.push(`${tintedSelectors.join(',\n')} {`);
    lines.push(
      `  --pkde-card-background: var(--color-${color.name}-50);`,
      `  --pkde-card-content: var(--color-neutral-950);`,
      `  --pkde-card-accent: var(--color-${color.name}-600);`,
      '}',
      '',
    );

    const boldSelectors = baseSelectors.map((selector) => `${selector} .pkde-card-bold`);
    lines.push(`${boldSelectors.join(',\n')} {`);
    lines.push(
      `  --pkde-card-background: var(--color-${cardColor.styles.background});`,
      `  --pkde-card-content: var(--color-${cardColor.styles.content});`,
      `  --pkde-card-accent: var(--color-${cardColor.styles.highlight});`,
      '}',
      '',
    );
  });

  return lines.join('\n');
}

function titleCase(slug) {
  return slug.split('-').map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');
}

/**
 * The editor's colour palette (theme.json settings.color.palette): the brand's own colours instead of Tailwind's 300-odd
 * swatches (vite.config.js sets disableTailwindColors). A short ladder per colour (the same oklch values as the CSS tokens,
 * written literally because the editor canvas only gets the --color-* variables a stylesheet actually uses), the exact source
 * colour for black/white, and a few of the tinted neutrals. Slugs match the Tailwind names, so `has-brand-600-background-color`
 * and `bg-brand-600` are the same colour.
 */
const PALETTE_STEPS = [50, 200, 400, 600, 800, 950];
const PALETTE_NEUTRAL_STEPS = [100, 300, 500, 700, 900];

function buildPalette(colors) {
  const entry = (slug, color) => `        { "slug": "${slug}", "name": "${titleCase(slug)}", "color": "${color}" }`;
  const rows = [];

  for (const color of colors) {
    if (color.role === 'black' || color.role === 'white') {
      rows.push(entry(color.name, color.hex));
      continue;
    }
    for (const step of PALETTE_STEPS) rows.push(entry(`${color.name}-${step}`, shade(color, step)));
  }

  const brand = colors.find((color) => color.role === 'brand') ?? colors[0];
  const brandOklch = toOklch(brand.hex);
  const tint = Math.min(0.02, (brandOklch?.c ?? 0) * 0.12);
  const tintHue = (brandOklch?.h ?? 0).toFixed(2);
  for (const step of PALETTE_NEUTRAL_STEPS) rows.push(entry(`neutral-${step}`, `oklch(${neutralLightness[step]} ${tint.toFixed(3)} ${tintHue})`));

  return rows.join(',\n');
}

/** Returns theme.json with settings.color.palette replaced by the generated list; every other byte is left alone. */
function withPalette(themeJson, colors) {
  const pattern = /("palette": \[)[\s\S]*?(\n {6}\])/;
  if (!pattern.test(themeJson)) fail('theme.json has no settings.color.palette array (expected `"palette": [` ... `      ]`).');
  return themeJson.replace(pattern, (_, open, close) => `${open}\n${buildPalette(colors)}${close}`);
}

/**
 * One canonical theme option list — every colour actually in the palette,
 * by its own real name — generated in both JS (for each themed block's
 * edit.jsx InspectorControls dropdown) and PHP (for bin/generate-demo-content.php,
 * which needs the same list to seed one demo instance per colour). Without
 * this, each block's edit.jsx previously hardcoded its own THEME_OPTIONS
 * array capped at 6 generic entries (alpha–foxtrot) — silently wrong the
 * moment a palette has more than 6 colours (this template's own default
 * palette has 8), and never in sync with what the palette actually
 * contains. `value` is the colour's real name (`.theme-coral`), not the
 * positional alias — buildSectionThemesCss's `.theme-{alias}` classes still
 * exist and still work, but a real, finite list generated fresh from the
 * actual palette every time doesn't need the "safe generic guess" an alias
 * was originally for. Includes the auto-added black/white neutrals (see
 * ensureNeutralRoles) the same as any other colour — a stark black or white
 * section is a real, selectable theme option, not just implementation detail.
 */
function buildThemeOptions(colors) {
  const options = [{ value: '', label: 'Default' }, ...colors.map((color) => ({ value: color.name, label: titleCase(color.name) }))];

  const js = [
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json.',
    ' * Do not edit directly. Import into any themed block\'s edit.jsx.',
    ' */',
    `export const THEME_OPTIONS = ${JSON.stringify(options, null, 2)};`,
    '',
  ].join('\n');

  const phpLines = [
    '<?php',
    '',
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json.',
    ' * Do not edit directly. Read by bin/generate-demo-content.php.',
    ' */',
    '',
    'return [',
    ...colors.map((color) => `    ['value' => '${color.name}', 'label' => '${titleCase(color.name).replace("'", "\\'")}'],`),
    '];',
    '',
  ];

  return { js, php: phpLines.join('\n') };
}

/**
 * `mono` is optional — most projects never need a third, monospace font (a
 * "HUD label"/code-style accent voice) alongside `display`/`sans`.
 *
 * Each font slot is either a plain string (a Google Fonts family name —
 * shorthand for `{ source: "google", family: <string> }`, unchanged from
 * every existing config) or an object naming its own `source` explicitly:
 * `"google"` (optionally overriding `weights`/`styles`/`subsets`) or
 * `"local"` (a project's own font files — `src` as a path/glob, or
 * `variants` for explicit per-file weight/style control). This only
 * validates the shape; vite.config.js's own `fonts:` option reads this same
 * config directly and does the actual work (self-hosting, variable-font
 * detection, preloading) — see that file's own comment.
 */
function validateFonts(fonts) {
  const validated = {};

  for (const slot of ['display', 'sans', 'mono']) {
    const value = fonts[slot];
    if (value === undefined) {
      if (slot === 'mono') continue;
      fail(`fonts.${slot} is required.`);
    }

    if (typeof value === 'string') {
      if (!value.trim()) fail(`fonts.${slot} must not be empty.`);
      validated[slot] = value;
      continue;
    }

    if (typeof value !== 'object' || value === null || Array.isArray(value)) {
      fail(`fonts.${slot} must be a Google Fonts family name (string) or an object with a "source".`);
    }
    if (!['google', 'local'].includes(value.source)) {
      fail(`fonts.${slot}.source must be "google" or "local".`);
    }
    if (typeof value.family !== 'string' || !value.family.trim()) {
      fail(`fonts.${slot}.family is required.`);
    }
    if (value.source === 'local' && !value.src && !value.variants) {
      fail(`fonts.${slot} has source "local" but no "src" or "variants" — vite.config.js's fonts pipeline needs to know which font file(s) to use.`);
    }
    validated[slot] = value;
  }

  return validated;
}

/**
 * The optional palette `header` setting: { "theme": "<colour name>" } makes the site header use that colour's own
 * section theme (the same generated .theme-{name} tokens every Hero/CTA uses), so a dark header can carry a white
 * logo and the nav follows the palette. Absent = today's light header, unchanged.
 *
 * Checked here, not left to the eye: the header's text (the colour's `content`) and hover (its `highlight`) must
 * each measure at least 4.5:1 (WCAG AA, normal text) against its `background`, resolved from that colour's own
 * `styles` exactly as the CSS will. A failing pair stops generation with the numbers, because the nav would
 * otherwise ship unreadable; fix the colour's `styles` in config/brand-palette.json or pick another colour.
 */
function validateHeader(header, colors) {
  if (header === undefined || header === null) return undefined;
  const theme = typeof header === 'object' ? header.theme : undefined;
  const colour = colors.find((candidate) => candidate.name === theme);
  if (!colour) {
    fail(`header.theme must be one of the palette colour names (${colors.map((candidate) => candidate.name).join(', ')}); got ${JSON.stringify(theme)}.`);
  }

  // A ref is NAME-STEP (a generated shade) or NAME-exact (the colour's untouched hex, see --color-NAME-exact).
  const resolve = (ref) => {
    const cut = ref.lastIndexOf('-');
    const owner = colors.find((candidate) => candidate.name === ref.slice(0, cut));
    if (!owner) return null;
    return ref.slice(cut + 1) === 'exact' ? owner.hex : shade(owner, Number(ref.slice(cut + 1)));
  };
  const background = resolve(colour.styles.background);
  for (const field of ['content', 'highlight']) {
    const foreground = resolve(colour.styles[field]);
    if (!background || !foreground) continue;
    const ratio = wcagContrast(foreground, background);
    if (ratio < 4.5) {
      fail(`header.theme "${colour.name}": the header's ${field} colour (${colour.styles[field]}) measures ${ratio.toFixed(2)}:1 on its background (${colour.styles.background}); it needs 4.5:1. Adjust that colour's styles in config/brand-palette.json or choose another header theme.`);
    }
  }

  return { theme: colour.name };
}

