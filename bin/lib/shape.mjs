/**
 * Global shape tokens (WP-108 A): the corner radius and the border thickness of the whole kit, declared in config/brand-palette.json under `shape`:
 *
 *   "shape": { "preset": "soft", "radius": { "sm": "0.5rem", "md": "1rem", "lg": "2rem", "full": "9999px" }, "border": { "thin": "1px", "thick": "2px" } }
 *
 * `preset` is sharp, soft (the default, and the kit's values before shape tokens existed: nothing changes visually) or round; `radius` and `border` override single tokens.
 * Three radius steps drive Tailwind's whole radius scale as exact multiples, so every `rounded-*` utility and every kit rule follows the three tokens and "soft" reproduces each
 * value the kit used (0.25rem is sm x 0.5, 0.75rem is sm x 1.5, 1.5rem is md x 1.5, 2rem is lg, ...).
 */
export const SHAPE_PRESETS = {
  sharp: { radius: { sm: '0px', md: '0px', lg: '0px', full: '0px' }, border: { thin: '1px', thick: '2px' } },
  soft: { radius: { sm: '0.5rem', md: '1rem', lg: '2rem', full: '9999px' }, border: { thin: '1px', thick: '2px' } },
  round: { radius: { sm: '0.75rem', md: '1.5rem', lg: '3rem', full: '9999px' }, border: { thin: '1px', thick: '2px' } },
};

const LENGTH = /^(0|\d*\.?\d+(px|rem|em))$/;

/** The Tailwind radius scale as multiples of the three tokens: name => [token, factor]. */
export const RADIUS_SCALE = {
  xs: ['sm', 0.25], sm: ['sm', 0.5], md: ['sm', 0.75], lg: ['sm', 1], xl: ['sm', 1.5], '2xl': ['md', 1], '3xl': ['md', 1.5], '4xl': ['lg', 1],
};

/**
 * @param {unknown} shape the `shape` object of the palette (undefined = soft)
 * @param {(message: string) => never} fail
 * @returns {{ preset: string, radius: Record<string, string>, border: Record<string, string> }}
 */
export function resolveShape(shape, fail) {
  if (shape === undefined || shape === null) return { preset: 'soft', ...structuredClone(SHAPE_PRESETS.soft) };
  if (typeof shape !== 'object' || Array.isArray(shape)) fail('shape must be an object: { "preset": "soft", "radius": {...}, "border": {...} }.');

  const preset = shape.preset ?? 'soft';
  if (!SHAPE_PRESETS[preset]) fail(`shape.preset must be one of ${Object.keys(SHAPE_PRESETS).join(', ')}; got ${JSON.stringify(preset)}.`);

  const resolved = { preset, radius: { ...SHAPE_PRESETS[preset].radius }, border: { ...SHAPE_PRESETS[preset].border } };

  for (const [group, keys] of [['radius', ['sm', 'md', 'lg', 'full']], ['border', ['thin', 'thick']]]) {
    for (const [key, value] of Object.entries(shape[group] ?? {})) {
      if (!keys.includes(key)) fail(`shape.${group}.${key} is not a token; use ${keys.join(', ')}.`);
      if (typeof value !== 'string' || !LENGTH.test(value.trim())) fail(`shape.${group}.${key} must be a length such as 0, 4px or 0.75rem; got ${JSON.stringify(value)}.`);
      resolved[group][key] = value.trim();
    }
  }

  return resolved;
}

/** The generated CSS: the tokens on :root and Tailwind's radius scale derived from them (static, so the kit's own var(--radius-*) rules always find them). */
export function buildShapeCss(shape) {
  const scale = Object.entries(RADIUS_SCALE).map(([name, [token, factor]]) => `  --radius-${name}: calc(var(--pkde-radius-${token}) * ${factor});`);

  return [
    '',
    '/* Shape tokens (shape in config/brand-palette.json, preset ' + shape.preset + '): the corner radius and the border thickness of every kit component. A site may set any of',
    '   them in its own CSS. Tailwind\'s radius scale below is derived from the three radius steps, so every rounded-* utility follows them. */',
    ':root {',
    ...Object.entries(shape.radius).map(([key, value]) => `  --pkde-radius-${key}: ${value};`),
    ...Object.entries(shape.border).map(([key, value]) => `  --pkde-border-${key}: ${value};`),
    '}',
    '',
    '@theme static {',
    ...scale,
    '}',
    '',
  ].join('\n');
}

/** resources/generated/shape.php: the tokens for the PHP side (the theme.json bridge, the drift check). */
export function buildShapePhp(shape) {
  const rows = (group) => Object.entries(shape[group]).map(([key, value]) => `        '${key}' => '${value}',`).join('\n');

  return [
    '<?php',
    '',
    '/**',
    ' * Generated by bin/generate-theme-tokens.mjs from config/brand-palette.json (shape).',
    ' * Do not edit directly. Read by the kit (app/shape.php) for theme.json and by the drift check.',
    ' */',
    '',
    'return [',
    `    'preset' => '${shape.preset}',`,
    "    'radius' => [",
    rows('radius'),
    '    ],',
    "    'border' => [",
    rows('border'),
    '    ],',
    '];',
    '',
  ].join('\n');
}
